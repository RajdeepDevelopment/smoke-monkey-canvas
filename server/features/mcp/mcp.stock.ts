// Attach a per-key link to every entry that still lacks an entry-level URL.
// Entries whose keys are all self-hosted config intentionally end up with
// neither, so the UI shows them as "your own value" rather than a dead link.
for (const entry of STOCK_MCPS) {
  const links: Record<string, { url: string; label: string }> = {};
  for (const key of entry.envKeys ?? []) {
    const hit = KEY_LINKS[key];
    if (hit) links[key] = hit;
  }
  if (Object.keys(links).length) entry.keyLinks = links;
  if (!entry.keyGetUrl) {
    const first = Object.values(links)[0];
    if (first) {
      entry.keyGetUrl = first.url;
      entry.keyGetLabel = first.label;
    }
  }
}
