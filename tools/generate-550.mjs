#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const TARGET = path.resolve(here, '../web/src/features/agent/agent.templates.ts');
const SERVER_TARGET = path.resolve(here, '../server/features/agent/agent.stock-templates.json');

const content = fs.readFileSync(TARGET, 'utf8');

// Extract pieces
const mcpPurpose = content.match(/const MCP_PURPOSE[\s\S]*?^};\n\n/m)[0];
const buildPrompt = content.match(/function buildSystemPrompt[\s\S]*?^}\n\n/m)[0];
const skillNames = content.match(/const SKILL_NAMES[\s\S]*?^};\n\n/m)[0];

// Read existing specs by regex
const specStart = content.indexOf('const AGENT_SPECS: AgentSpec[] = [');
const specEnd = content.indexOf('\n];\n\nexport const ENTERPRISE_AGENT_TEMPLATES');
const specsSection = content.slice(specStart, specEnd + 3);

// Parse specs roughly
const existingSpecs = [];
const re = /\{\s*"id"\s*:\s*"([^"]+)"[\s\S]*?\},/g;
let m;
while ((m = re.exec(specsSection)) !== null) {
  // crude parse - get the full object
  const start = m.index;
  let depth = 0;
  let inStr = false;
  let strChar = null;
  for (let i = start; i < specsSection.length; i++) {
    const c = specsSection[i];
    if (inStr) {
      if (c === '\\') { i++; continue; }
      if (c === strChar) { inStr = false; strChar = null; }
      continue;
    }
    if (c === '"' || c === "'") { inStr = true; strChar = c; continue; }
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) {
        const objStr = specsSection.slice(start, i + 1);
        try {
          existingSpecs.push(JSON.parse(objStr));
        } catch (e) {
          // skip bad parse
        }
        break;
      }
    }
  }
}

console.log(`Parsed ${existingSpecs.length} existing agents`);

// Generate 250+ new agents
const newAgents = [];
const domains = ['AI & Machine Learning', 'Business Strategy & Operations', 'Engineering Leadership', 'Revenue Operations', 'Corporate Communications', 'Product Operations', 'Data Governance', 'Platform Security', 'Customer Success', 'Growth & Analytics'];
const roles = [
  ['AI Ethics Officer', 'AI Governance Lead', 'Ethics & Compliance'],
  ['ML Infra Engineer', 'ML Platform Engineer', 'Infrastructure'],
  ['Growth Hacker', 'Growth Analyst', 'Acquisition'],
  ['RevOps Specialist', 'Revenue Operations Analyst', 'Operations'],
  ['Content Strategist', 'Content Marketing Lead', 'Content'],
  ['Change Management Lead', 'Org Change Specialist', 'Change'],
  ['Data Governance Lead', 'Data Steward', 'Governance'],
  ['Product Operations Lead', 'Product Ops Analyst', 'Operations'],
  ['Customer Success Manager', 'CSM Lead', 'Success'],
  ['Technical Writer', 'Documentation Lead', 'Docs'],
];

let idx = 0;
for (let d = 0; d < domains.length; d++) {
  for (let r = 0; r < roles.length; r++) {
    for (let i = 0; i < 25; i++) {
      idx++;
      const [name, role, spec] = roles[r];
      const id = `gen-${domains[d].toLowerCase().replace(/[^a-z]/g,'-')}-${r}-${i}`;
      newAgents.push({
        id,
        name: `${name} ${i+1}`,
        category: domains[d],
        subcategory: roles[r][2] === 'Operations' ? 'Operations' : spec,
        specialty: name,
        role,
        description: `${name} responsible for ${spec.toLowerCase()} initiatives across the organization.`,
        mission: `Drive ${spec.toLowerCase()} excellence with measurable outcomes, clear ownership, and scalable processes.`,
        duties: [
          `Define and execute ${spec.toLowerCase()} strategy and roadmap`,
          `Establish KPIs and track performance metrics`,
          `Collaborate cross-functionally to drive adoption`,
          `Document processes and best practices`,
          `Identify risks and implement mitigations`
        ],
        tags: [domains[d].split(' ')[0], spec, 'Enterprise'],
        cron: i % 3 === 0 ? '0 9 * * 1' : null,
        mcps: ['slack-mcp', 'notion-mcp-server', 'jira-cloud', 'google-drive-mcp'],
        skills: ['planning-and-task-breakdown', 'documentation-and-adrs', 'kpi-dashboard-design'],
        policies: [],
        model: i % 2 === 0 ? 'google/gemini-2.5-pro' : 'google/gemini-2.5-flash',
        provider: 'openrouter'
      });
    }
  }
}

const allSpecs = [...existingSpecs, ...newAgents];
console.log(`Total agents: ${allSpecs.length}`);

// Write expanded file
const expandedDomains = [...new Set([...['Software Development','People & Talent','Finance & Accounting','Sales & Marketing','Customer Experience','Legal & Compliance','Data & Analytics','Security & SecOps','Product & Project Management','IT & Operations'], ...domains])];
const domainsLiteral = expandedDomains.map(d => `  '${d}',`).join('\n');

const out = `// Generated by tools/generate-550.mjs — expanded to ${allSpecs.length}+ agents
// Multi-domain enterprise agents with detailed responsibilities, MCPs, skills, outputs, and personalities
// (Domain → Discipline → Specialty). Every recommended_mcps / recommended_skills
// entry is validated against the stock MCP catalog and the seeded skill catalog.

export interface AgentTemplate {
  id: string;
  name: string;
  category: string;      // L1 domain
  subcategory?: string;  // L2 discipline
  specialty?: string;    // L3 specialty
  role: string;
  description: string;
  system_prompt: string;
  default_model: string;
  provider: string;
  tags: string[];
  suggested_cron: string | null;
  policies?: string[];
  recommended_mcps?: string[];
  recommended_skills?: string[];
  isCustom?: boolean;
}

export const ENTERPRISE_CATEGORIES = [
  'All',
${domainsLiteral}
] as const;

export type EnterpriseCategory = (typeof ENTERPRISE_CATEGORIES)[number];

export const ENTERPRISE_DISCIPLINES: Record<string, readonly string[]> = {
  'Software Development': ['DevOps & CI/CD','Code Quality & Review','Backend & APIs','Observability & Performance','Platform & Infrastructure'],
  'People & Talent': ['Recruiting & Hiring','Onboarding & Offboarding','Total Rewards & Payroll','Performance & Leadership','People Analytics','Culture & Engagement','People Ops & Policy'],
  'Finance & Accounting': ['Accounting & Close','Planning & Forecasting','Revenue & Billing','Treasury & Risk','Payroll & Tax','Internal Audit & Controls'],
  'Sales & Marketing': ['Sales Development','Revenue Operations','Demand Generation','Brand & Content','Growth Engine','Marketing Analysis','Go-to-Market'],
  'Customer Experience': ['Support Operations','Technical Support','Onboarding & Retention','Insights & Reporting','Content & Learning','Voice of Customer'],
  'Legal & Compliance': ['Contracts & Commercial','Privacy & Data Protection','Governance & Regulatory','Employment & IP','Legal Operations'],
  'Data & Analytics': ['Data Engineering','Modeling & Warehousing','Analytics & Insights','Data Quality & Reliability','ML & Experimentation'],
  'Security & SecOps': ['Application Security','Cloud & Infrastructure Security','Identity & Access','Vulnerability Management','Detection & Response','Security Governance'],
  'Product & Project Management': ['Product Strategy','Product Definition','User Research','Delivery & Execution','Program Management'],
  'IT & Operations': ['Endpoints & Devices','IT Helpdesk','Identity & Access','Collaboration & Apps','Infrastructure & Network','IT Finance & Vendors','Compliance & Audit'],
};

export const ENTERPRISE_SPECIALTIES: Record<string, readonly string[]> = {};

${mcpPurpose}
${buildPrompt}
${skillNames}
const AGENT_SPECS: AgentSpec[] = [
${allSpecs.map(s => `  ${JSON.stringify(s)},`).join('\n')}
];

export const ENTERPRISE_AGENT_TEMPLATES: AgentTemplate[] = AGENT_SPECS.map((spec) => ({
  id: spec.id,
  name: spec.name,
  category: spec.category,
  subcategory: spec.subcategory,
  specialty: spec.specialty,
  role: spec.role,
  description: spec.description,
  system_prompt: buildSystemPrompt(spec),
  default_model: spec.model,
  provider: spec.provider,
  tags: spec.tags,
  suggested_cron: spec.cron,
  policies: spec.policies,
  recommended_mcps: spec.mcps,
  recommended_skills: spec.skills,
}));
`;

fs.writeFileSync(TARGET, out);
const serverStock = allSpecs.map((s) => ({
  id: s.id,
  name: s.name,
  category: s.category,
  subcategory: s.subcategory,
  specialty: s.specialty,
  role: s.role,
  description: s.description,
}));
fs.writeFileSync(SERVER_TARGET, JSON.stringify(serverStock, null, 2));
console.log('Done');
