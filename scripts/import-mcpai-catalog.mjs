#!/usr/bin/env node
// Regenerate server/features/mcp/mcp.stock.mcpai.ts from the public MCP.ai
// catalogue.
//
//   node scripts/import-mcpai-catalog.mjs            # full refresh
//   node scripts/import-mcpai-catalog.mjs --limit 50 # smoke test
//
// The catalogue is discovered from https://mcp.ai/sitemap.xml (one page per
// toolkit slug) and described by https://api.mcp.ai/api/<slug>/_endpoints.
// Every published toolkit is a hosted remote MCP endpoint at
// https://api.mcp.ai/p_<slug> that advertises MCP OAuth (protected-resource
// metadata + dynamic client registration + PKCE), so the shared Connect flow
// works for all of them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = path.join(ROOT, 'server/features/mcp/mcp.stock.mcpai.ts');
const CACHE = path.join(ROOT, 'node_modules/.cache/mcpai-catalog.jsonl');
const UA = { 'user-agent': 'smoke-monkey-canvas catalog import' };
const WORKERS = Number(process.env.WORKERS || 20);
const LIMIT = Number(process.argv.includes('--limit') ? process.argv[process.argv.indexOf('--limit') + 1] : 0);

const SKIP = new Set(['explore', 'prompts', 'pricing', 'blog', 'docs', 'login', 'signup', 'en', 'es', 'ko', 'zh']);

async function discoverSlugs() {
  const res = await fetch('https://mcp.ai/sitemap.xml', { headers: UA });
  if (!res.ok) throw new Error(`sitemap ${res.status}`);
  const xml = await res.text();
  const slugs = [];
  const seen = new Set();
  for (const m of xml.matchAll(/<loc>([^<]+)<\/loc>/g)) {
    let p;
    try {
      p = new URL(m[1]).pathname.replace(/^\/|\/$/g, '');
    } catch {
      continue;
    }
    if (!p || p.includes('/') || SKIP.has(p) || seen.has(p)) continue;
    seen.add(p);
    slugs.push(p);
  }
  return LIMIT ? slugs.slice(0, LIMIT) : slugs;
}

async function describe(slug) {
  try {
    const res = await fetch(`https://api.mcp.ai/api/${encodeURIComponent(slug)}/_endpoints`, {
      headers: UA,
      signal: AbortSignal.timeout(20000),
    });
    if (!res.ok) return null;
    const j = await res.json();
    if (!j?.slug || !Array.isArray(j.endpoints)) return null;
    return {
      slug: j.slug,
      name: typeof j.name === 'string' && j.name.trim() ? j.name.trim() : j.slug,
      tools: j.endpoints.length,
      auth: Array.isArray(j.auth) ? j.auth : [],
    };
  } catch {
    return null;
  }
}

async function main() {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  const done = new Map();
  if (fs.existsSync(CACHE)) {
    for (const line of fs.readFileSync(CACHE, 'utf8').split('\n')) {
      if (!line.trim()) continue;
      try {
        const rec = JSON.parse(line);
        done.set(rec.slug, rec);
      } catch {}
    }
  }

  const slugs = await discoverSlugs();
  const pending = slugs.filter((s) => !done.has(s));
  console.log(`catalogue: ${slugs.length} slugs, ${pending.length} pending`);

  let cursor = 0;
  const cacheStream = fs.createWriteStream(CACHE, { flags: 'a' });
  async function worker() {
    while (cursor < pending.length) {
      const slug = pending[cursor++];
      const rec = await describe(slug);
      if (rec) {
        done.set(rec.slug, rec);
        cacheStream.write(JSON.stringify(rec) + '\n');
      }
      if (cursor % 200 === 0) console.log(`  ${cursor}/${pending.length}`);
    }
  }
  await Promise.all(Array.from({ length: WORKERS }, worker));
  cacheStream.end();

  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const recs = [...done.values()].filter((r) => /^[a-z0-9_]+$/.test(r.slug)).sort((a, b) => a.slug.localeCompare(b.slug));

  const body = recs
    .map((r) => {
      const name = r.name || r.slug;
      const oauth = r.auth.includes('oauth_bearer');
      const auth = oauth ? 'oauth' : 'api_key';
      const iconUrl = r.iconUrl || `https://mcp-ai-public-assets.s3.amazonaws.com/logos/${r.slug}.svg`;
      return `  { name: 'mcpai-${r.slug}', label: '${esc(name)}', category: 'MCP.ai Catalog', description: '${desc}', url: 'https://api.mcp.ai/p_${r.slug}', envKeys: [], authType: '${auth}', iconUrl: '${iconUrl}' },`;
    })
    .join('\n');

  const header = `// Generated by scripts/import-mcpai-catalog.mjs. Do not hand-edit; re-run the
// import to refresh. Every entry is a hosted remote MCP endpoint at
// https://api.mcp.ai/p_<slug> that advertises MCP OAuth (protected-resource
// metadata + dynamic client registration + PKCE), so Connect uses the shared
// authorization flow.
import type { StockMcp } from './mcp.stock.js';

export const MCPAI_MCPS: StockMcp[] = [
`;
  fs.writeFileSync(OUT_FILE, `${header}${body}\n];\n`);
  console.log(`wrote ${recs.length} entries (${Math.round(fs.statSync(OUT_FILE).size / 1024)} KB) → ${path.relative(ROOT, OUT_FILE)}`);
}

await main();
